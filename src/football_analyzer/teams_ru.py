def transliterate(name: str) -> str:
    """Простая транслитерация: читаемо, но не «перевод»."""
    result = []
    for character in name.lower():
        if character in _LATIN:
            result.append(_LATIN[character])
        elif character.isalpha():
            result.append(character)
        elif character in " -&.":
            result.append(character)
    text = "".join(result).strip()
    return " ".join(word[:1].upper() + word[1:] for word in text.split())


def to_russian(name: str) -> str:
    """Русское имя команды: из словаря, иначе транслитерация."""
    if name in TEAMS_RU:
        return TEAMS_RU[name]
    # Иногда ESPN добавляет суффиксы вроде «AFC» — пробуем без них.
    for suffix in (" AFC", " FC", " FK"):
        if name.endswith(suffix) and name[: -len(suffix)] in TEAMS_RU:
            return TEAMS_RU[name[: -len(suffix)]]
    return transliterate(name)
