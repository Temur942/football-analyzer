-- =============================================================================
-- football-analyzer — пульс бота и напоминания о продлении (009).
--
-- heartbeat: если бот жив, он каждые 10 минут пишет время. Нет записи дольше
-- 30 минут — значит процесс упал или потерял сеть; без этого «бот молчит»
-- замечает только заказчик.
-- =============================================================================

CREATE TABLE IF NOT EXISTS heartbeat (
    name       TEXT PRIMARY KEY,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
